"""Pretraining study configuration loading, aggregation, and statistical contracts."""

import json
import math
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np

from scripts.tuning_experiments import HparamConfig
from scripts.tuning_records import hardware_evidence as tuning_hardware_evidence
from scripts.tuning_records import source_hashes as tuning_source_hashes

ROOT = Path(__file__).resolve().parents[1]
PRETRAINING_TOKEN_BUDGET = 2_500_000_000
PRETRAINING_SEEDS = (42, 43, 44)
PRETRAINING_ARCHITECTURES = ("algebraic", "baseline")


def load_verified_tuning_configs(results_dir: Path) -> Dict[str, HparamConfig]:
    """Load frozen winners only when current Tuning study evidence is valid."""
    results_dir = Path(results_dir)
    metrics_path = results_dir / "metrics.json"
    result = tuning_hardware_evidence(metrics_path, tuning_source_hashes())
    metrics_record = (
        json.loads(metrics_path.read_text()) if metrics_path.exists() else {}
    )
    verification_path = results_dir / "verification.json"
    verification = (
        json.loads(verification_path.read_text()) if verification_path.exists() else {}
    )
    aggregate_valid = (
        verification.get("passed") is True
        and verification.get("status") == "PASS"
        and verification.get("environment", {}).get("source_sha256")
        == tuning_source_hashes()
        and (results_dir / "PASS.md").exists()
    )
    hardware_valid = (
        result.get("passed", False)
        and metrics_record.get("passed") is True
        and metrics_record.get("status") == "PASS"
        and metrics_record.get("environment", {}).get("source_sha256")
        == tuning_source_hashes()
    )
    if not (hardware_valid or (result.get("passed", False) and aggregate_valid)):
        raise RuntimeError(
            "Pretraining study requires a current Tuning study PASS generated by the corrected "
            "multi-candidate protocol; "
            f"hardware validation: {result}; aggregate validation: {aggregate_valid}"
        )

    configs = {
        "algebraic": HparamConfig(**json.loads(
            (results_dir / "algebraic_optimal.json").read_text()
        )),
        "baseline": HparamConfig(**json.loads(
            (results_dir / "baseline_optimal.json").read_text()
        )),
    }
    if configs["algebraic"].schedule != "ards":
        raise ValueError("algebraic Tuning study winner must use the ARDS schedule")
    if configs["baseline"].schedule != "cosine":
        raise ValueError("baseline Tuning study winner must use the cosine schedule")
    return configs


def latest_checkpoint(directory: Path) -> Path | None:
    checkpoints = sorted(Path(directory).glob("step-*.pkl"))
    return checkpoints[-1] if checkpoints else None


def summarize_pretraining(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Validate the six paired runs and compute pretraining statistics."""
    expected_pairs = {
        (architecture, seed)
        for architecture in PRETRAINING_ARCHITECTURES
        for seed in PRETRAINING_SEEDS
    }
    actual_pairs = [(row.get("architecture"), row.get("seed")) for row in records]
    complete = len(actual_pairs) == len(expected_pairs) and set(actual_pairs) == expected_pairs

    grouped = {
        architecture: [
            row for row in records if row.get("architecture") == architecture
        ]
        for architecture in PRETRAINING_ARCHITECTURES
    }
    stats: Dict[str, Any] = {}
    for architecture, rows in grouped.items():
        losses = np.asarray([row.get("validation_loss", np.nan) for row in rows], dtype=np.float64)
        perplexities = np.asarray(
            [row.get("validation_perplexity", np.nan) for row in rows], dtype=np.float64
        )
        n = len(rows)
        stats[f"{architecture}_mean_validation_loss"] = (
            float(np.mean(losses)) if n else None
        )
        stats[f"{architecture}_mean_perplexity"] = (
            float(np.mean(perplexities)) if n else None
        )
        stats[f"{architecture}_perplexity_sem"] = (
            float(np.std(perplexities, ddof=1) / math.sqrt(n)) if n > 1 else None
        )
        sem = stats[f"{architecture}_perplexity_sem"]
        mean = stats[f"{architecture}_mean_perplexity"]
        stats[f"{architecture}_perplexity_ci95"] = (
            [float(mean - 4.30265273 * sem), float(mean + 4.30265273 * sem)]
            if n == 3 and np.isfinite(mean) and np.isfinite(sem)
            else None
        )

    alg_ppl = stats["algebraic_mean_perplexity"]
    base_ppl = stats["baseline_mean_perplexity"]
    ratio = (
        alg_ppl / base_ppl
        if alg_ppl is not None and base_ppl is not None and base_ppl > 0
        else None
    )
    normalization_pass = complete and all(
        row.get("architecture") != "algebraic"
        or (
            row.get("normalization_second_moment_min", 0.0) >= 0.8
            and row.get("normalization_second_moment_max", 999.0) <= 1.3
        )
        for row in records
    )
    safety_pass = complete and all(
        row.get("total_tokens", 0) >= PRETRAINING_TOKEN_BUDGET
        and row.get("nan_or_inf_count") == 0
        and row.get("loss_spike_count") == 0
        and row.get("peak_gradient_norm", float("inf")) <= 5.0
        for row in records
    ) and normalization_pass
    return {
        "completed_runs": len(records),
        "expected_runs": 6,
        "complete_pairing": complete,
        "minimum_tokens_per_run": min(
            (row.get("total_tokens", 0) for row in records), default=0
        ),
        "perplexity_ratio": ratio,
        "pretraining_safety_passed": safety_pass,
        "normalization_second_moment_passed": normalization_pass,
        "perplexity_parity_passed": bool(
            ratio is not None and np.isfinite(ratio) and ratio <= 1.08
        ),
        **stats,
    }
